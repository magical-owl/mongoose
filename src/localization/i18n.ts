export type TranslationKey = keyof typeof translations.en;

export function translate(language: AppLanguage, key: TranslationKey): string {
  return translations[language][key] ?? translations.en[key];
}

export function useTranslation(): (key: TranslationKey) => string {
  const language = useAppStore((state) => state.appLanguage);
  return (key: TranslationKey) => translate(language, key);
}

export function homeViewModeLabel(mode: HomeViewMode, t: (key: TranslationKey) => string): string {
  if (mode === 'timeline') return t('homeTimeline');
  if (mode === 'feed') return t('homeFeed');
  return t('homeCard');
}

export function homeFilterKindLabel(kind: string, t: (key: TranslationKey) => string): string {
  if (kind === 'date') return t('homeFilterDate');
  if (kind === 'tag') return t('homeFilterTag');
  if (kind === 'mood') return t('homeFilterMood');
  return t('homeFilterCompanion');
}

export function homeFilterAllLabel(kind: string, t: (key: TranslationKey) => string): string {
  if (kind === 'date') return t('homeFilterAllDates');
  if (kind === 'tag') return t('homeFilterAllTags');
  if (kind === 'mood') return t('homeFilterAllMoods');
  return t('homeFilterAllCompanions');
}

export function reflectionCountLabel(count: number, t: (key: TranslationKey) => string): string {
  return `${count} ${count === 1 ? t('reflection') : t('reflections')}`;
}

export function appText(value: string): string {
  return value
    .replaceAll('{appName}', APP_IDENTITY.codename)
    .replaceAll('{premiumName}', APP_IDENTITY.premiumName);
}

export function premiumPaywallTitle(t: (key: TranslationKey) => string): string {
  return appText(t('premiumPaywallTitle'));
}

